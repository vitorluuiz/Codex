function makePhase(
  id: string,
  num: number,
  name: string,
  kind: PhaseKind,
  question: string,
  correctAnswerText: string,
  accuracyRate: number,
  avgScore: number,
  avgElapsedSeconds: number,
  correctCount: number,
  incorrectCount: number,
  options: ReportOptionDistribution[] = [],
): ReportPhaseAnalysis {
  return {
    phaseId: id,
    orderIndex: num - 1,
    phaseNumber: num,
    setTitle: 'Algoritmos & Estruturas de Dados',
    kind,
    name,
    question,
    basePoints: 100,
    pointsMultiplier: 1.0,
    maxScore: 100,
    timeSeconds: 60,
    correctAnswerText,
    submittedCount: 5,
    correctCount,
    incorrectCount,
    unansweredCount: 0,
    pendingCount: 0,
    accuracyRate,
    avgScore,
    avgElapsedSeconds,
    mostCommonAnswerText: correctAnswerText,
    optionDistribution: options,
  };
}

function makeAnswer(
  phase: ReportPhaseAnalysis,
  correct: boolean,
  score: number,
  elapsed: number,
  givenAnswer: string,
): ReportParticipantAnswer {
  return {
    phaseId: phase.phaseId,
    phaseNumber: phase.phaseNumber,
    phaseName: phase.name,
    kind: phase.kind,
    question: phase.question,
    submitted: true,
    grading: 'graded',
    correct,
    score,
    maxScore: phase.maxScore,
    classAvgScore: phase.avgScore,
    classAccuracyRate: phase.accuracyRate,
    elapsedSeconds: elapsed,
    timeSeconds: phase.timeSeconds,
    givenAnswerText: givenAnswer,
    correctAnswerText: phase.correctAnswerText,
    explanation: null,
  };
}

