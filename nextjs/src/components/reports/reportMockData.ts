function makeParticipant(
  id: string,
  userId: string | null,
  name: string,
  avatar: AvatarIndex,
  token: string,
  rank: number,
  score: number,
  correctCount: number,
  elapsed: number,
  answersDef: Array<{
    correct: boolean;
    score: number;
    elapsed: number | null;
    text: string;
    submitted?: boolean;
  }>,
): ReportParticipantAnalysis {
  const unansweredCount = answersDef.filter((a) => a.submitted === false).length;
  const gradedCount = 4 - unansweredCount;
  return {
    participantId: id,
    userId,
    displayName: name,
    avatarIndex: avatar,
    rank,
    percentile: Math.round(((5 - rank + 1) / 5) * 100),
    accessToken: token,
    joinedAt: new Date(Date.now() - 1000 * 60 * 20).toISOString(),
    totalScore: score,
    maxPossibleScore: 400,
    scorePercentage: Math.round((score / 400) * 100),
    gradedCount,
    correctCount,
    incorrectCount: gradedCount - correctCount,
    unansweredCount,
    pendingCount: 0,
    accuracyRate: gradedCount > 0 ? Math.round((correctCount / gradedCount) * 100) : 0,
    totalElapsedSeconds: elapsed,
    avgElapsedSeconds: Math.round((elapsed / 4) * 10) / 10,
    answers: mockPhases.map((phase, idx) => {
      const a = answersDef[idx]!;
      return makeAnswer(phase, a.correct, a.score, a.elapsed, a.text, a.submitted ?? true);
    }),
  };
}

