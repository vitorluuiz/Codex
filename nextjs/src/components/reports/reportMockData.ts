function makeParticipant(
  id: string,
  userId: string | null,
  name: string,
  avatar: AvatarIndex,
  token: string,
  rank: number,
  score: number,
  correctCount: number,
  elapsed: number,
  answersDef: Array<{ correct: boolean; score: number; elapsed: number; text: string }>,
): ReportParticipantAnalysis {
  return {
    participantId: id,
    userId,
    displayName: name,
    avatarIndex: avatar,
    rank,
    percentile: Math.round(((5 - rank + 1) / 5) * 100),
    accessToken: token,
    joinedAt: new Date(Date.now() - 1000 * 60 * 20).toISOString(),
    totalScore: score,
    maxPossibleScore: 400,
    scorePercentage: Math.round((score / 400) * 100),
    gradedCount: 4,
    correctCount,
    incorrectCount: 4 - correctCount,
    unansweredCount: 0,
    pendingCount: 0,
    accuracyRate: Math.round((correctCount / 4) * 100),
    totalElapsedSeconds: elapsed,
    avgElapsedSeconds: Math.round(elapsed / 4),
    answers: mockPhases.map((phase, idx) => {
      const a = answersDef[idx]!;
      return makeAnswer(phase, a.correct, a.score, a.elapsed, a.text);
    }),
  };
}

